def make_loaders(folder, batch_train=64, batch_eval=128, seed=SEED):
    X = np.load(f'{folder}/images.npy').astype(np.float32) / 255.0
    y = np.load(f'{folder}/labels.npy')
    X = X[:, None, :, :]                                  # (N, 1, H, W)
    y_min = (y[:, 0] * 60 + y[:, 1]).astype(np.int64)     # minutes since 12:00, 0-719

    idx = np.random.default_rng(seed).permutation(len(X))
    n_tr, n_va = 14400, 1800
    tr, va, te = idx[:n_tr], idx[n_tr:n_tr + n_va], idx[n_tr + n_va:]

    X_t, y_t = torch.from_numpy(X), torch.from_numpy(y_min)
    mean, std = X_t[tr].mean(), X_t[tr].std()
    X_t = (X_t - mean) / std

    ds = lambda i: TensorDataset(X_t[i], y_t[i])
    loaders = (DataLoader(ds(tr), batch_size=batch_train, shuffle=True),
               DataLoader(ds(va), batch_size=batch_eval,  shuffle=False),
               DataLoader(ds(te), batch_size=batch_eval,  shuffle=False))
    del X, X_t
    return loaders


