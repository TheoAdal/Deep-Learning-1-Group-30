"""## 3. Model

A multi-head CNN: a shared convolutional backbone, then a 256-unit fully connected
layer, then two classification heads (12 hours, 60 minutes).

Each block is `conv 3x3 -> [BatchNorm] -> ReLU -> maxpool 2x2`. Setting `dil > 1`
enlarges the receptive field without changing the number of parameters or the spatial
size of the feature maps, which is what separates the receptive field from the size of
the flatten layer.
"""

class MultiHeadClock(nn.Module):
    def __init__(self, channels=(32, 64, 128), fc=256, img=150, dil=1, bn=False):
        super().__init__()
        layers, c = [], 1
        for ch in channels:
            layers.append(nn.Conv2d(c, ch, 3, padding=dil, dilation=dil))
            if bn:
                layers.append(nn.BatchNorm2d(ch))
            layers += [nn.ReLU(), nn.MaxPool2d(2)]
            c = ch
        self.features = nn.Sequential(*layers)
        with torch.no_grad():
            self.flat = self.features(torch.zeros(1, 1, img, img)).numel()
        self.shared = nn.Sequential(nn.Flatten(), nn.Linear(self.flat, fc), nn.ReLU())
        self.hour_head = nn.Linear(fc, 12)
        self.min_head  = nn.Linear(fc, 60)

    def forward(self, x):
        z = self.shared(self.features(x))
        return self.hour_head(z), self.min_head(z)


def receptive_field(n_blocks, dil=1):
    """Theoretical RF of the last conv layer, for n blocks of conv3x3 + maxpool2."""
    r, j = 1, 1
    for _ in range(n_blocks):
        r += 2 * dil * j      # 3x3 conv with dilation dil
        r += j                # 2x2 max pool
        j *= 2
    return r


print({n: receptive_field(n) for n in (3, 4, 5)}, '| dilated 3 blocks:', receptive_field(3, 3))

"""## 4. Training and evaluation

The metric is the common-sense error: with `d = (prediction - target) mod 720`, the
error is `min(d, 720 - d)` in minutes, averaged over the set. The loss is the sum of
the cross-entropies of the two heads.
"""

def common_sense_error(pred_min, true_min):
    d = np.abs(np.asarray(pred_min) - np.asarray(true_min)) % 720
    return np.minimum(d, 720 - d).mean()


mh_target = lambda y: torch.stack([y // 60, y % 60], dim=1)
mh_to_min = lambda out: (out[0].argmax(1) * 60 + out[1].argmax(1)).cpu().numpy()


def mh_criterion(out, target, alpha=1.0):
    h_out, m_out = out
    return (nn.functional.cross_entropy(h_out, target[:, 0])
            + alpha * nn.functional.cross_entropy(m_out, target[:, 1]))


def train_one_epoch(model, loader, optimizer):
    model.train()
    running = 0.0
    for images, y in loader:
        images, targets = images.to(device), mh_target(y).to(device)
        optimizer.zero_grad()
        loss = mh_criterion(model(images), targets)
        loss.backward()
        optimizer.step()
        running += loss.item() * images.size(0)
    return running / len(loader.dataset)


def evaluate(model, loader):
    model.eval()
    preds, trues = [], []
    with torch.no_grad():
        for images, t in loader:
            preds.append(mh_to_min(model(images.to(device))))
            trues.append(t.numpy())
    return common_sense_error(np.concatenate(preds), np.concatenate(trues))


def run(tag, train_dl, val_dl, n_blocks, img, dil=1, bn=False,
        lr=3e-4, epochs=30, seed=SEED, verbose=True):
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)

    channels = (32, 64, 128, 256, 256)[:n_blocks]
    model = MultiHeadClock(channels=channels, img=img, dil=dil, bn=bn).to(device)
    optimizer = optim.Adam(model.parameters(), lr=lr)

    hist = {'train_loss': [], 'val_cse': []}
    t0 = time.time()
    for epoch in range(1, epochs + 1):
        tr = train_one_epoch(model, train_dl, optimizer)
        va = evaluate(model, val_dl)
        hist['train_loss'].append(tr)
        hist['val_cse'].append(va)
        if verbose:
            print(f'[{tag}] epoch {epoch:2d}: train loss {tr:.4f} | val CSE {va:.1f} min')

    return {'tag': tag, 'blocks': n_blocks, 'input': img, 'dilation': dil, 'batchnorm': bn,
            'rf': receptive_field(n_blocks, dil), 'flatten': model.flat,
            'best_val_cse': min(hist['val_cse']),
            'best_epoch': int(np.argmin(hist['val_cse'])) + 1,
            'final_val_cse': hist['val_cse'][-1],
            'time_s': round(time.time() - t0, 1),
            'history': hist, 'model': model}

